#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-2.0-only
"""Generate the camera stack's register tables from the Linux sources.

Nothing in the generated headers is typed in by hand: every register
offset, bit and value comes from the Leste kernel tree (Linux 7.1 with the
Pro1X patches, build/linux), so it can be regenerated and checked:

  gen-tables.py LINUX_TREE [CAMERA_DIR]   (default: this script's ../)

into CAMERA_DIR/sys/arm64/qualcomm/camss/ (kernel) and
CAMERA_DIR/tools/pro1x-cam/ (user space):

  camss_gcc_sm6115.h     drivers/clk/qcom/gcc-sm6115.c: the camera's branch
                         clocks, their RCGs (frequency tables, parent maps),
                         the PLLs they come from, the GDSCs;
                         include/dt-bindings/clock/qcom,gcc-sm6115.h: the
                         device tree's clock numbers
  camss_csiphy_qcm2290.h drivers/media/platform/qcom/camss/
                         camss-csiphy-3ph-1-0.c: lane_regs_qcm2290
  camss_tlmm_sm6115.h    drivers/pinctrl/qcom/pinctrl-sm6115.c: each GPIO's
                         tile and its functions (the mux value is the index)
  sensor_tables.h        drivers/media/i2c/imx582.c, s5k4h7.c, dw9800.c: the
                         register sequences, modes, the supplies in the
                         order the drivers enable them (user space)
"""
import os
import re
import sys

LINUX = sys.argv[1]
CAM = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(
    os.path.abspath(__file__)), '..')
KDIR = os.path.join(CAM, 'sys/arm64/qualcomm/camss')
UDIR = os.path.join(CAM, 'tools/pro1x-cam')


def read(rel):
    with open(os.path.join(LINUX, rel)) as f:
        return f.read()


def num(s):
    if s is None:
        return 0
    s = s.strip()
    if s.startswith('BIT('):
        return 1 << int(s[4:-1], 0)
    return int(s, 0)


HDR = ('/* Generated by freebsd/camera/gen/gen-tables.py from %s; do not edit. */\n')

# --- GCC -----------------------------------------------------------------------
gcc = read('drivers/clk/qcom/gcc-sm6115.c')
bind = read('include/dt-bindings/clock/qcom,gcc-sm6115.h')
dtnum = {m.group(1): int(m.group(2)) for m in
         re.finditer(r'#define\s+(GCC_\w+)\s+(\d+)', bind)}

parent_maps = {}
for m in re.finditer(r'static const struct parent_map (\w+)\[\] = \{(.*?)\};', gcc, re.S):
    parent_maps[m.group(1)] = re.findall(r'\{ (P_\w+), (\d+) \}', m.group(2))

ftbls = {}
for m in re.finditer(r'static const struct freq_tbl (\w+)\[\] = \{(.*?)\};', gcc, re.S):
    ents = []
    for e in re.finditer(r'F\((\d+), (P_\w+), ([\d.]+), (\d+), (\d+)\)', m.group(2)):
        h = float(e.group(3))
        ents.append((int(e.group(1)), e.group(2), int(2 * h - 1),
                     int(e.group(4)), int(e.group(5))))
    ftbls[m.group(1)] = ents


def field(body, key):
    m = re.search(r'\.' + key + r'\s*=\s*([^,\n]+),', body)
    return m.group(1).strip() if m else None


rcgs = {}
for m in re.finditer(r'static struct clk_rcg2 (\w+) = \{(.*?)\n\};', gcc, re.S):
    b = m.group(2)
    rcgs[m.group(1)] = dict(cmd=num(field(b, 'cmd_rcgr')),
                            mnd=num(field(b, 'mnd_width')),
                            hid=num(field(b, 'hid_width')),
                            pmap=field(b, 'parent_map'),
                            ftbl=field(b, 'freq_tbl'))

branches = {}
for m in re.finditer(r'static struct clk_branch (\w+) = \{(.*?)\n\};', gcc, re.S):
    b = m.group(2)
    par = re.search(r'parent_hws = .*?&(\w+)\.clkr', b, re.S)
    branches[m.group(1)] = dict(halt=num(field(b, 'halt_reg')),
                                check=field(b, 'halt_check'),
                                en=num(field(b, 'enable_reg')),
                                mask=num(field(b, 'enable_mask')),
                                parent=par.group(1) if par else None)

plls = {}
for m in re.finditer(r'static struct clk_alpha_pll (\w+) = \{(.*?)\n\};', gcc, re.S):
    b = m.group(2)
    plls[m.group(1)] = dict(off=num(field(b, 'offset')),
                            en=num(field(b, 'enable_reg')),
                            mask=num(field(b, 'enable_mask')))
postdivs = {}
for m in re.finditer(r'static struct clk_alpha_pll_postdiv (\w+) = \{(.*?)\n\};', gcc, re.S):
    b = m.group(2)
    postdivs[m.group(1)] = dict(off=num(field(b, 'offset')),
                                table=field(b, 'post_div_table'))
pdtables = {}
for m in re.finditer(r'static const struct clk_div_table (\w+)\[\] = \{(.*?)\};', gcc, re.S):
    pdtables[m.group(1)] = [(int(a, 0), int(b, 0)) for a, b in
                            re.findall(r'\{ (0x[0-9a-f]+|\d+), (\d+) \}', m.group(2))]
pllcfg = {}
for m in re.finditer(r'static const struct alpha_pll_config (\w+) = \{(.*?)\n\};', gcc, re.S):
    d = {}
    for k, v in re.findall(r'\.(\w+)\s*=\s*((?:[^,\n()]|\([^)]*\))+),', m.group(2)):
        v = v.strip()
        g = re.match(r'GENMASK\((\d+), (\d+)\)', v)
        if g:
            hi, lo = int(g.group(1)), int(g.group(2))
            d[k] = ((1 << (hi - lo + 1)) - 1) << lo
            continue
        s = re.match(r'(0x[0-9a-fA-F]+|\d+) << (\d+)', v)
        if s:
            d[k] = int(s.group(1), 0) << int(s.group(2))
            continue
        d[k] = num(v)
    pllcfg[m.group(1)] = d

gdscs = {}
for m in re.finditer(r'static struct gdsc (\w+) = \{(.*?)\n\};', gcc, re.S):
    b = m.group(2)
    gdscs[m.group(1)] = dict(reg=num(field(b, 'gdscr')),
                             votable='VOTABLE' in (field(b, 'flags') or ''))

# The sources: P_<PLL>_OUT_<x> -> the PLL and, for postdiv outputs, the divider
SRC_PLL = {}
for p in parent_maps.values():
    for src, _ in p:
        mm = re.match(r'P_(GPLL\d+)_OUT_(\w+)', src)
        if mm:
            SRC_PLL[src] = mm.group(1).lower()

# what the camera uses: every gcc_camss_* / gcc_camera_* branch, their RCGs
cam_br = sorted(k for k in branches if k.startswith(('gcc_camss_', 'gcc_camera_')))
cam_rcg = sorted({branches[k]['parent'] for k in cam_br if branches[k]['parent']})
used_src = sorted({e[1] for r in cam_rcg for e in ftbls[rcgs[r]['ftbl']]})
used_pll = sorted({SRC_PLL[s] for s in used_src if s in SRC_PLL})

out = [HDR % 'drivers/clk/qcom/gcc-sm6115.c, include/dt-bindings/clock/qcom,gcc-sm6115.h']
out.append('#ifndef _CAMSS_GCC_SM6115_H_\n#define _CAMSS_GCC_SM6115_H_\n')
out.append('/* clock sources (the parent maps\' P_* names) */')
out.append('enum camss_src {')
for s in used_src:
    out.append('\tCAMSS_%s,' % s)
out.append('\tCAMSS_NSRC\n};\n')
out.append('static const char *const camss_src_name[CAMSS_NSRC] = {')
for s in used_src:
    out.append('\t[CAMSS_%s] = "%s",' % (s, s[2:].lower()))
out.append('};\n')
out.append('/* alpha PLLs (type DEFAULT_EVO): mode register offset, FSM vote bit */')
out.append('struct camss_pll { const char *name; uint32_t off, vote_reg, vote_mask; };')
out.append('enum camss_pll_id {')
for p in used_pll:
    out.append('\tCAMSS_PLL_%s,' % p.upper())
out.append('\tCAMSS_NPLL\n};')
out.append('static const struct camss_pll camss_plls[CAMSS_NPLL] = {')
for p in used_pll:
    d = plls[p]
    out.append('\t[CAMSS_PLL_%s] = { "%s", %#x, %#x, %#x },' % (p.upper(), p, d['off'], d['en'], d['mask']))
out.append('};\n')
out.append('/* which PLL feeds a source (-1: the crystal), and its post divider\n'
           ' * (the clk_alpha_pll_postdiv table: field value -> divider) */')
out.append('static const int camss_src_pll[CAMSS_NSRC] = {')
for s in used_src:
    out.append('\t[CAMSS_%s] = %s,' % (s, ('CAMSS_PLL_' + SRC_PLL[s].upper()) if s in SRC_PLL else '-1'))
out.append('};\n')
# postdiv outputs used: gpllN_out_main / out_aux2 have tables
out.append('struct camss_postdiv { int src; uint32_t off; u_int nent; uint8_t val[4], div[4]; };')
out.append('static const struct camss_postdiv camss_postdivs[] = {')
for name, d in sorted(postdivs.items()):
    mm = re.match(r'(gpll\d+)_out_(\w+)', name)
    src = 'P_%s_OUT_%s' % (mm.group(1).upper(), mm.group(2).upper())
    if src not in used_src:
        continue
    t = pdtables[d['table']]
    out.append('\t{ CAMSS_%s, %#x, %d, { %s }, { %s } },' % (
        src, d['off'], len(t), ', '.join('%#x' % a for a, _ in t),
        ', '.join(str(b) for _, b in t)))
out.append('};\n')
for p in used_pll:
    cfgname = p + '_config'
    if cfgname not in pllcfg:
        continue
    c = pllcfg[cfgname]
    out.append('/* %s, written by Linux\'s gcc_sm6115_probe (clk_alpha_pll_configure) */' % cfgname)
    for k in sorted(c):
        out.append('#define\tCAMSS_%s_%s\t%#x' % (p.upper(), k.upper(), c[k]))
    out.append('')
out.append('/* RCGs: command register, M/N/D and HID widths, frequency table\n'
           ' * (pre_div is the register value 2 * h - 1, as F() stores it) */')
out.append('struct camss_freq { uint32_t freq; uint8_t src, pre_div; uint16_t m, n; };')
out.append('struct camss_rcg { const char *name; uint32_t cmd; uint8_t mnd, hid;\n'
           '\tint8_t sel[CAMSS_NSRC];\t/* parent map: source -> CFG SRC_SEL, -1 none */\n'
           '\tu_int nfreq; struct camss_freq freq[16]; };')
out.append('enum camss_rcg_id {')
for r in cam_rcg:
    out.append('\tCAMSS_RCG_%s,' % r[4:-8].upper())
out.append('\tCAMSS_NRCG\n};')
out.append('static const struct camss_rcg camss_rcgs[CAMSS_NRCG] = {')
for r in cam_rcg:
    d = rcgs[r]
    pm = dict(parent_maps[d['pmap']])
    sel = ', '.join('[CAMSS_%s] = %s' % (s, pm[s]) for s in used_src if s in pm)
    nosel = [s for s in used_src if s not in pm]
    sel = ', '.join(['[CAMSS_%s] = -1' % s for s in nosel] + ([sel] if sel else []))
    ents = ftbls[d['ftbl']]
    out.append('\t[CAMSS_RCG_%s] = { "%s", %#x, %d, %d,\n\t    { %s },\n\t    %d, {' % (
        r[4:-8].upper(), r, d['cmd'], d['mnd'], d['hid'], sel, len(ents)))
    for e in ents:
        out.append('\t\t{ %d, CAMSS_%s, %d, %d, %d },' % e)
    out.append('\t} },')
out.append('};\n')
out.append('/* branch clocks: device tree number, halt register and check, enable\n'
           ' * register and bit, the RCG behind it (-1: none) */')
out.append('enum camss_halt { CAMSS_HALT, CAMSS_HALT_VOTED, CAMSS_HALT_DELAY };')
out.append('struct camss_branch { const char *name; int dt; uint32_t halt;\n'
           '\tuint8_t check; uint32_t en, mask; int rcg; };')
out.append('enum camss_branch_id {')
for b in cam_br:
    out.append('\tCAMSS_CLK_%s,' % b[4:].upper())
out.append('\tCAMSS_NBRANCH\n};')
out.append('static const struct camss_branch camss_branches[CAMSS_NBRANCH] = {')
for b in cam_br:
    d = branches[b]
    dt = dtnum.get(b.upper(), -1)
    chk = {'BRANCH_HALT': 'CAMSS_HALT', 'BRANCH_HALT_VOTED': 'CAMSS_HALT_VOTED',
           'BRANCH_HALT_DELAY': 'CAMSS_HALT_DELAY'}[d['check']]
    rcg = ('CAMSS_RCG_' + d['parent'][4:-8].upper()) if d['parent'] else '-1'
    out.append('\t[CAMSS_CLK_%s] = { "%s", %d, %#x, %s, %#x, %#x, %s },' % (
        b[4:].upper(), b, dt, d['halt'], chk, d['en'], d['mask'], rcg))
out.append('};\n')
out.append('/* GDSCs: the camera\'s and the multimedia SMMU TBUs\' (HLOS votes) */')
for g in ('gcc_camss_top_gdsc', 'hlos1_vote_mm_snoc_mmu_tbu_rt_gdsc',
          'hlos1_vote_mm_snoc_mmu_tbu_nrt_gdsc'):
    d = gdscs[g]
    out.append('#define\tCAMSS_GDSC_%s\t%#x%s' % (
        g.replace('gcc_', '').replace('hlos1_vote_mm_snoc_mmu_', '').replace('_gdsc', '').upper(),
        d['reg'], '\t/* VOTABLE */' if d['votable'] else ''))
gdt = re.search(r'/\* Indexes for GDSCs \*/(.*)', bind, re.S).group(1)
for n, v in re.findall(r'#define\s+(\w+_GDSC)\s+(\d+)', gdt):
    if n in ('GCC_CAMSS_TOP_GDSC', 'HLOS1_VOTE_MM_SNOC_MMU_TBU_RT_GDSC',
             'HLOS1_VOTE_MM_SNOC_MMU_TBU_NRT_GDSC'):
        out.append('#define\tCAMSS_DT_%s\t%s\t/* power-domains index */' % (n, v))
out.append('\n#endif')
with open(os.path.join(KDIR, 'camss_gcc_sm6115.h'), 'w') as f:
    f.write('\n'.join(out) + '\n')

# --- CSIPHY --------------------------------------------------------------------
cs = read('drivers/media/platform/qcom/camss/camss-csiphy-3ph-1-0.c')
m = re.search(r'csiphy_lane_regs lane_regs_qcm2290\[\] = \{(.*?)\n\};', cs, re.S)
ents = re.findall(r'\{(0x[0-9a-fA-F]+), (0x[0-9a-fA-F]+), (0x[0-9a-fA-F]+), (CSIPHY_\w+)\}',
                  m.group(1))
out = [HDR % 'drivers/media/platform/qcom/camss/camss-csiphy-3ph-1-0.c (lane_regs_qcm2290)']
out.append('/* address, value, delay (us), kind: as csiphy_gen2_config_lanes() uses it */')
out.append('static const struct csiphy_lane_reg csiphy_lane_regs_qcm2290[] = {')
for a, v, d, k in ents:
    out.append('\t{ %s, %s, %s, %s },' % (a.lower(), v.lower(), d, k))
out.append('};')
with open(os.path.join(KDIR, 'camss_csiphy_qcm2290.h'), 'w') as f:
    f.write('\n'.join(out) + '\n')

# --- TLMM ----------------------------------------------------------------------
pc = read('drivers/pinctrl/qcom/pinctrl-sm6115.c')
for k, v in (('mux_bit', '2'), ('pull_bit', '0'), ('drv_bit', '6'), ('oe_bit', '9'),
             ('in_bit', '0'), ('out_bit', '1')):
    assert re.search(r'\.%s = %s,' % (k, v), pc), k     # the layout used below
groups = re.findall(r'\[(\d+)\] = PINGROUP\((\d+), (\w+), ([^)]*)\)', pc)
out = [HDR % 'drivers/pinctrl/qcom/pinctrl-sm6115.c']
out.append('/* CTL at 0x1000 * gpio of its tile: pull bits 0-1, function (mux) bits\n'
           ' * 2-5, drive bits 6-8, OE bit 9; IO at +4: in bit 0, out bit 1 */')
out.append('#define\tTLMM_NPINS\t%d' % len(groups))
out.append('enum tlmm_tile { TLMM_WEST, TLMM_SOUTH, TLMM_EAST };')
out.append('static const struct { uint8_t tile; const char *func[10]; } tlmm_pins[TLMM_NPINS] = {')
for idx, gid, tile, funcs in groups:
    assert idx == gid
    f = ['"gpio"'] + [('NULL' if x.strip() == '_' else '"%s"' % x.strip())
                      for x in funcs.split(',')]
    out.append('\t[%s] = { TLMM_%s, { %s } },' % (idx, tile, ', '.join(f)))
out.append('};')
with open(os.path.join(KDIR, 'camss_tlmm_sm6115.h'), 'w') as f:
    f.write('\n'.join(out) + '\n')

# --- sensors -------------------------------------------------------------------
out = [HDR % 'drivers/media/i2c/imx582.c, drivers/media/i2c/s5k4h7.c']
out.append('#ifndef _SENSOR_TABLES_H_\n#define _SENSOR_TABLES_H_\n')
out.append('struct reg8 { uint16_t reg; uint8_t val; };')
out.append('struct sensor_mode { const char *name; uint32_t width, height, hts, vts_def;\n'
           '\tuint64_t pixel_rate; u_int link_freq_idx; const struct reg8 *regs; u_int nregs; };\n')


def seqs(src):
    r = {}
    for m in re.finditer(r'static const struct cci_reg_sequence (\w+)\[\] = \{(.*?)\n\};', src, re.S):
        e = re.findall(r'\{ CCI_REG8\((0x[0-9a-fA-F]+)\), (0x[0-9a-fA-F]+) \}', m.group(2))
        assert len(e) == m.group(2).count('{'), m.group(1)   # only 8-bit writes
        r[m.group(1)] = e
    return r


def modes(src, arr):
    m = re.search(r'static const struct \w+ ' + arr + r'\[\] = \{(.*?)\n\};', src, re.S)
    res = []
    for blk in re.findall(r'\n\t\{(.*?)\n\t\}', m.group(1), re.S):
        g = lambda k: re.search(r'\.' + k + r' = (\w+),', blk)
        res.append(dict(w=int(g('width').group(1)), h=int(g('height').group(1)),
                        hts=int(g('hts').group(1)), vts=int(g('vts_def').group(1)),
                        pr=g('pixel_rate') and int(g('pixel_rate').group(1)),
                        lf=g('link_freq_idx') and int(g('link_freq_idx').group(1)),
                        regs=re.search(r'\.regs = (\w+)', blk).group(1)))
    return res


def defines(src, names):
    d = {}
    for n in names:
        m = re.search(r'#define\s+' + n + r'\s+(.+)', src)
        d[n] = m.group(1).split('/*')[0].strip()
    return d


for name, path, arr, pre in (('imx582', 'drivers/media/i2c/imx582.c', 'imx582_modes', 'IMX582'),
                             ('s5k4h7', 'drivers/media/i2c/s5k4h7.c', 's5k4h7_modes', 'S5K4H7')):
    src = read(path)
    for sname, e in seqs(src).items():
        out.append('static const struct reg8 %s[] = {' % sname)
        for a, v in e:
            out.append('\t{ %s, %s },' % (a.lower(), v.lower()))
        out.append('};')
    d = defines(src, [pre + '_' + k for k in ('REG_CHIP_ID', 'CHIP_ID', 'STREAMING_REG',
                                               'EXP_REG', 'EXP_MARGIN', 'EXP_MIN',
                                               'AGAIN_REG', 'AGAIN_MIN', 'AGAIN_MAX',
                                               'FRAME_LENGTH_REG', 'VTS_MAX')])
    for k, v in d.items():
        v = re.sub(r'CCI_REG(8|16)\((0x[0-9a-fA-F]+)\)', r'\2', v)
        out.append('#define\t%s\t%s' % (k, v))
    # the link frequencies (Hz)
    lf = re.search(r'static const s64 %s_link_freq_menu_items\[\] = \{(.*?)\};' % name, src, re.S)
    vals = re.findall(r'(\d{6,})', lf.group(1))
    if not vals:            # s5k4h7: { S5K4H7_LINK_FREQ }, (367 * HZ_PER_MHZ)
        mhz = re.search(r'#define\s+%s_LINK_FREQ\s+\((\d+) \* HZ_PER_MHZ\)' % pre, src)
        vals = [str(int(mhz.group(1)) * 1000000)]
    out.append('static const uint64_t %s_link_freqs[] = { %s };' % (name, ', '.join(vals)))
    pr = re.search(r'#define\s+%s_PIXEL_RATE\s+(\d+)' % pre, src)
    code = re.search(r'MEDIA_BUS_FMT_(S[RGB]{4})10_1X10', src).group(1)
    out.append('#define\t%s_BAYER\t"%s"\t/* MEDIA_BUS_FMT_%s10_1X10 */' % (pre, code[1:], code))
    sup = re.search(r'static const char \*const %s_supply_name\[\] = \{(.*?)\};' % name, src, re.S)
    out.append('/* the supplies in the order %s_power_on() enables them */' % name)
    out.append('static const char *const %s_supplies[] = { %s, NULL };' % (
        name, ', '.join(re.findall(r'"\w+"', sup.group(1)))))
    out.append('static const struct sensor_mode %s_modes[] = {' % name)
    for mo in modes(src, arr):
        prate = mo['pr'] if mo['pr'] else int(pr.group(1))
        out.append('\t{ "%dx%d", %d, %d, %d, %d, %d, %d, %s, nitems(%s) },' % (
            mo['w'], mo['h'], mo['w'], mo['h'], mo['hts'], mo['vts'], prate,
            mo['lf'] or 0, mo['regs'], mo['regs']))
    out.append('};\n')
dw = read('drivers/media/i2c/dw9800.c')
sup = re.search(r'static const char \*const dw9800_supply_name\[\] = \{(.*?)\};', dw, re.S)
out.append('static const char *const dw9800_supplies[] = { %s, NULL };' %
           ', '.join(re.findall(r'"\w+"', sup.group(1))))
for k, v in defines(dw, ['DW9800_MAX_FOCUS_POS', 'DW9800_CTRL_STEPS', 'DW9800_CTRL_DELAY_US',
                         'DW9800_CTL_ADDR', 'DW9800_MSB_ADDR', 'DW9800_LSB_ADDR',
                         'DW9800_STATUS_ADDR', 'DW9800_MAX_RETRY']).items():
    out.append('#define\t%s\t%s' % (k, v))
out.append('\n#endif')
with open(os.path.join(UDIR, 'sensor_tables.h'), 'w') as f:
    f.write('\n'.join(out) + '\n')
print('generated into', KDIR, 'and', UDIR)
