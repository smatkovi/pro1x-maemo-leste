#!/bin/bash
# Graft Debian's armhf glibc and Mesa into a Harmattan rootfs.
#
# Harmattan's own GL stack is the PowerVR SGX driver of the N9/N950, which
# cannot work on the Adreno 610. Debian's Mesa needs a current glibc, so
# the glibc of Harmattan (eglibc 2.10) is replaced as a whole; Harmattan's
# 2012 binaries keep working thanks to glibc's symbol versioning. Only libc
# itself used GLIBC_PRIVATE, so nothing else depends on its internals.
#
# Every Harmattan file that is replaced is moved to
# /usr/lib/harmattan-replaced (same relative path), and both lists are
# written to /var/lib/pro1x-graft/, so 'undo' restores the original state.
#
#   D=/host/debian-armhf H=/mnt/harmattan bash meego/30-graft-debian-runtime.sh [graft|undo]
set -eu

D=${D:-/host/debian-armhf}
H=${H:-/mnt/harmattan}
MODE=${1:-graft}

STATE=$H/var/lib/pro1x-graft
SAVE=$H/usr/lib/harmattan-replaced
TRIPLET=arm-linux-gnueabihf
ML=usr/lib/$TRIPLET
TOOLS=$(cd "$(dirname "$0")" && pwd)/tools

ROOTS=$(sed 's/#.*//' "$(dirname "$0")/debian-packages.list")

# Paths of a package that are not taken over: Debian config and docs.
skip_path() {
	case "$1" in
	/etc/*|/usr/share/doc/*|/usr/share/man/*|/usr/share/lintian/*|/usr/share/bug/*) return 0 ;;
	/usr/share/locale/*|/usr/share/info/*|/var/*|/usr/lib/systemd/*) return 0 ;;
	esac
	return 1
}

soname() {
	readelf -d "$1" 2>/dev/null | sed -n 's/.*(SONAME).*\[\(.*\)\]/\1/p'
}

# Follow a symlink inside $H: absolute targets point into $H, not the host.
resolve() {
	local p=$1 t n=0
	while [ -L "$H$p" ] && [ $n -lt 16 ]; do
		t=$(readlink "$H$p")
		case "$t" in /*) p=$t ;; *) p=$(dirname "$p")/$t ;; esac
		n=$((n + 1))
	done
	echo "$p"
}

undo() {
	[ -f "$STATE/added" ] || { echo "nothing to undo"; exit 0; }
	while read -r p; do
		rm -f "$H$p"
	done < "$STATE/added"
	if [ -f "$STATE/converted" ]; then
		while read -r p; do
			mv -f "$SAVE$p" "$H$p"
		done < "$STATE/converted"
	fi
	while read -r p; do
		mkdir -p "$(dirname "$H$p")"
		mv -f "$SAVE$p" "$H$p"
	done < "$STATE/moved"
	rm -rf "$STATE" "$SAVE"
	chroot "$H" /sbin/ldconfig
	echo "Harmattan runtime restored"
}

graft() {
	[ -f "$STATE/added" ] && { echo "already grafted (run 'undo' first)"; exit 1; }
	mkdir -p "$STATE" "$SAVE"
	: > "$STATE/added"
	: > "$STATE/moved"

	# Runtime dependency closure of the root packages, installed ones only.
	local pkgs
	pkgs=$(chroot "$D" apt-cache depends --recurse --installed --no-recommends \
		--no-suggests --no-conflicts --no-breaks --no-replaces --no-enhances \
		$ROOTS 2>/dev/null | sed -n 's/^\([a-z0-9][^ :<]*\).*/\1/p' | sort -u)
	# Bootstrapping packages that only matter to Debian's own system.
	pkgs=$(echo "$pkgs" | grep -vxE 'debconf|dpkg|tar|perl-base|base-files|debianutils|sysvinit-utils|init-system-helpers|usrmerge|libc-l10n|mawk|gcc-14-base')
	echo "$pkgs" > "$STATE/packages"

	local files=$STATE/files
	: > "$files"
	for p in $pkgs; do
		chroot "$D" dpkg-query -L "$p" 2>/dev/null || true
	done | sort -u | while read -r f; do
		skip_path "$f" && continue
		[ -d "$D$f" ] && [ ! -L "$D$f" ] && continue
		[ -e "$D$f" ] || [ -L "$D$f" ] || continue
		echo "$f"
	done > "$files"
	# Locales generated by 20-debian-armhf.sh are not owned by a package.
	[ -f "$D/usr/lib/locale/locale-archive" ] && echo /usr/lib/locale/locale-archive >> "$files"

	# Sonames that Debian now provides. Harmattan copies of them, wherever
	# its loader would look, must go, or the old library could win.
	local sonames=$STATE/sonames
	while read -r f; do
		case "$f" in *.so*) ;; *) continue ;; esac
		[ -f "$D$f" ] && [ ! -L "$D$f" ] || continue
		soname "$D$f"
	done < "$files" | sort -u > "$sonames"

	local dirs="/lib /usr/lib"
	for c in "$H"/etc/ld.so.conf.d/*.conf; do
		dirs="$dirs $(grep -v '^#' "$c" 2>/dev/null)"
	done

	move() {
		local p=$1
		grep -qxF "$p" "$STATE/moved" && return 0
		mkdir -p "$(dirname "$SAVE$p")"
		mv "$H$p" "$SAVE$p"
		echo "$p" >> "$STATE/moved"
	}

	for d in $dirs; do
		case "$d" in /lib/$TRIPLET|/usr/lib/$TRIPLET) continue ;; esac
		[ -d "$H$d" ] || continue
		for f in "$H$d"/*.so*; do
			[ -e "$f" ] || [ -L "$f" ] || continue
			local rel=${f#$H} name s=""
			name=$(basename "$f")
			[ -f "$f" ] && [ ! -L "$f" ] && s=$(soname "$f")
			# eglibc 2.10 pieces Debian no longer ships (nis, cidn, SegFault...)
			case "$name" in
			*-2.10.1.so|libSegFault.so|libpcprofile.so|libmemusage.so|libthread_db*.so*)
				if [ "$d" = /lib ]; then move "$rel"; continue; fi ;;
			esac
			if grep -qxF "$name" "$sonames" || { [ -n "$s" ] && grep -qxF "$s" "$sonames"; }; then
				move "$rel"
			fi
		done
	done
	# Links whose target was just moved (libc.so.6 -> libc-2.10.1.so, the
	# old name libexpat.so.0 -> libexpat.so.1 ...) point at Debian's library
	# with that soname, or go as well when Debian has none.
	for d in /lib /usr/lib; do
		for l in "$H$d"/*.so*; do
			[ -L "$l" ] || continue
			local rel=${l#$H} t s
			t=$(resolve "$rel")
			[ -e "$H$t" ] && continue
			[ -f "$SAVE$t" ] || continue
			s=$(soname "$SAVE$t")
			if [ -n "$s" ] && grep -qxF "$s" "$sonames" && [ "$(basename "$rel")" != "$s" ]; then
				move "$rel"
				ln -s "/$ML/$s" "$H$rel"
				echo "$rel" >> "$STATE/added"
			else
				move "$rel"
			fi
		done
	done

	# The PowerVR SGX driver of the N9 (its libraries carry unversioned
	# sonames such as libEGL.so, which ldconfig would link again).
	for f in "$H"/usr/lib/*_r125.so; do
		[ -e "$f" ] || continue
		local s
		s=$(soname "$f")
		move "${f#$H}"
		if [ -n "$s" ] && { [ -e "$H/usr/lib/$s" ] || [ -L "$H/usr/lib/$s" ]; }; then
			move "/usr/lib/$s"
		fi
	done

	# Harmattan's locale archive and its tools go as well.
	for p in /usr/lib/locale/locale-archive /sbin/ldconfig /usr/bin/iconv /usr/bin/locale \
		/usr/bin/localedef /usr/bin/getconf /usr/bin/ldd /usr/bin/getent /usr/bin/catchsegv; do
		if [ -e "$H$p" ] || [ -L "$H$p" ]; then move "$p"; fi
	done

	# Copy Debian's files.
	while read -r f; do
		if [ -e "$H$f" ] || [ -L "$H$f" ]; then
			[ -d "$H$f" ] && [ ! -L "$H$f" ] && continue
			move "$f"
		fi
		mkdir -p "$(dirname "$H$f")"
		cp -a "$D$f" "$H$f"
		echo "$f" >> "$STATE/added"
	done < "$files"

	# Harmattan has no merged /usr: provide the paths its binaries use.
	link() {
		local target=$1 p=$2
		if [ -e "$H$p" ] || [ -L "$H$p" ]; then move "$p"; fi
		mkdir -p "$(dirname "$H$p")"
		ln -s "$target" "$H$p"
		echo "$p" >> "$STATE/added"
	}
	# Harmattan binaries ask for /lib/ld-linux.so.3, armhf's libc for
	# ld-linux-armhf.so.3: both are Debian's armhf loader.
	link /$ML/ld-linux-armhf.so.3 /lib/ld-linux.so.3
	link /$ML/ld-linux-armhf.so.3 /lib/ld-linux-armhf.so.3
	echo "/lib/$TRIPLET
/usr/lib/$TRIPLET" > "$H/etc/ld.so.conf.d/$TRIPLET.conf"
	echo "/etc/ld.so.conf.d/$TRIPLET.conf" >> "$STATE/added"
	link /usr/sbin/ldconfig /sbin/ldconfig
	# Harmattan links the unversioned SGX names.
	link /$ML/libEGL.so.1 /usr/lib/libEGL.so
	link /$ML/libGLESv2.so.2 /usr/lib/libGLESv2.so
	link /$ML/libGLESv1_CM.so.1 /usr/lib/libGLES_CM.so
	for f in eglinfo es2_info es2gears_x11 eglgears_x11; do
		[ -e "$H/usr/bin/$f.$TRIPLET" ] && link "$f.$TRIPLET" "/usr/bin/$f"
	done

	chroot "$H" /sbin/ldconfig

	# Harmattan is prelinked; current glibc ignores the RELA tables prelink
	# made on ARM. Convert them back to REL (originals kept for 'undo').
	: > "$STATE/converted"
	find "$H/bin" "$H/sbin" "$H/lib" "$H/usr" "$H/opt" -xdev -type f \
		\( -name '*.so*' -o -perm -u+x \) \
		-not -path "$SAVE/*" -not -path "$H/$ML/*" 2>/dev/null |
		python3 "$TOOLS/rela2rel.py" --list | while read -r f; do
		local rel=${f#$H}
		mkdir -p "$(dirname "$SAVE$rel")"
		cp -a "$f" "$SAVE$rel"
		echo "$rel" >> "$STATE/converted"
	done
	if [ -s "$STATE/converted" ]; then
		sed "s|^|$H|" "$STATE/converted" | xargs python3 "$TOOLS/rela2rel.py" > /dev/null
	fi

	echo "grafted: $(wc -l < "$STATE/added") files added, $(wc -l < "$STATE/moved") Harmattan files moved to ${SAVE#$H}, $(wc -l < "$STATE/converted") prelinked files converted"
}

case "$MODE" in
graft) graft ;;
undo) undo ;;
*) echo "usage: $0 [graft|undo]"; exit 1 ;;
esac
